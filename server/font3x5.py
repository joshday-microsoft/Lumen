UNKNOWN = ("###", "#.#", "#.#", "#.#", "###")

GLYPH_W = 3
GLYPH_H = 5


def glyph(ch: str):
    return GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or UNKNOWN


def measure(text: str, scale: int = 1, spacing: int = 1) -> tuple[int, int]:
    """Pixel width/height of a single line of text."""
    n = len(text)
    if n == 0:
        return (0, GLYPH_H * scale)
    w = n * GLYPH_W * scale + (n - 1) * spacing * scale
    return (w, GLYPH_H * scale)
